// ─── Client-facing enhancement report (PDF) ────────────────
// A one-or-two page PDF the user can hand to the client: what their existing
// site scored, what was wrong with it, and exactly what ForgeAI improved.
// Streams straight to the HTTP response — nothing is written to disk.

import PDFDocument from 'pdfkit'
import type { Writable } from 'stream'
import type { SiteAudit } from './siteAudit'

const INK = '#111827'
const MUTED = '#6b7280'
const BRAND = '#0f766e'
const LINE = '#e5e7eb'

export interface ReportInput {
  siteName: string
  sourceUrl?: string
  liveUrl?: string
  audit?: SiteAudit
  enhancements: string[]
  generatedAt?: Date
}

export function writeEnhancementReport(out: Writable, input: ReportInput): void {
  const doc = new PDFDocument({ size: 'A4', margin: 50, info: { Title: `${input.siteName} — Website Enhancement Report` } })
  doc.pipe(out)

  const W = doc.page.width - 100 // usable width inside margins
  const date = (input.generatedAt ?? new Date()).toLocaleDateString('en-GB', {
    day: 'numeric', month: 'long', year: 'numeric',
  })

  // ── Header ──
  doc.fillColor(BRAND).fontSize(9).font('Helvetica-Bold').text('WEBSITE ENHANCEMENT REPORT', { characterSpacing: 1.2 })
  doc.moveDown(0.4)
  doc.fillColor(INK).fontSize(24).font('Helvetica-Bold').text(input.siteName)
  doc.moveDown(0.25)
  doc.fillColor(MUTED).fontSize(10).font('Helvetica')
  if (input.sourceUrl) doc.text(`Original site: ${input.sourceUrl}`)
  if (input.liveUrl) doc.text(`Enhanced site: ${input.liveUrl}`)
  doc.text(`Prepared ${date}`)
  doc.moveDown(0.8)
  doc.moveTo(50, doc.y).lineTo(doc.page.width - 50, doc.y).strokeColor(LINE).lineWidth(1).stroke()
  doc.moveDown(1)

  // ── Score ──
  if (input.audit) {
    const a = input.audit
    const boxTop = doc.y
    doc.roundedRect(50, boxTop, W, 74, 8).fillColor('#f9fafb').fill()
    doc.fillColor(BRAND).fontSize(34).font('Helvetica-Bold')
      .text(`${a.score.toFixed(1)}`, 66, boxTop + 16, { continued: true })
      .fillColor(MUTED).fontSize(14).font('Helvetica').text(' / 10')
    doc.fillColor(INK).fontSize(12).font('Helvetica-Bold')
      .text(a.headline, 160, boxTop + 18, { width: W - 130 })
    doc.fillColor(MUTED).fontSize(9).font('Helvetica')
      .text(a.reasoning, 160, doc.y + 2, { width: W - 130 })
    doc.y = boxTop + 86

    // Category bars
    doc.fillColor(INK).fontSize(11).font('Helvetica-Bold').text('How the original site scored')
    doc.moveDown(0.5)
    for (const c of a.categories) {
      const y = doc.y
      doc.fillColor(INK).fontSize(9).font('Helvetica').text(c.name, 50, y, { width: 130 })
      const barX = 185, barW = W - 185 + 50 - 60
      doc.roundedRect(barX, y + 1, barW, 8, 4).fillColor('#e5e7eb').fill()
      const pct = Math.max(0.02, c.score / 10)
      doc.roundedRect(barX, y + 1, barW * pct, 8, 4)
        .fillColor(c.score >= 7 ? '#16a34a' : c.score >= 4 ? '#f59e0b' : '#dc2626').fill()
      doc.fillColor(MUTED).fontSize(9).font('Helvetica')
        .text(`${c.score.toFixed(1)}`, barX + barW + 8, y, { width: 30 })
      doc.y = y + 15
    }
    doc.moveDown(0.6)

    if (a.issues.length) {
      doc.fillColor(INK).fontSize(11).font('Helvetica-Bold').text('Problems found on the original site')
      doc.moveDown(0.35)
      doc.fillColor(MUTED).fontSize(9.5).font('Helvetica')
      for (const issue of a.issues.slice(0, 8)) doc.text(`•  ${issue}`, { indent: 6 })
      doc.moveDown(0.8)
    }
  }

  // ── What was improved ──
  if (doc.y > doc.page.height - 220) doc.addPage()
  doc.fillColor(INK).fontSize(13).font('Helvetica-Bold').text('What we improved')
  doc.moveDown(0.5)
  doc.fontSize(9.5).font('Helvetica')
  for (const item of input.enhancements) {
    const y = doc.y
    doc.fillColor(BRAND).font('Helvetica-Bold').text('✓', 52, y, { width: 14 })
    doc.fillColor(INK).font('Helvetica').text(item, 68, y, { width: W - 22 })
    doc.moveDown(0.45)
  }

  doc.moveDown(0.8)
  doc.moveTo(50, doc.y).lineTo(doc.page.width - 50, doc.y).strokeColor(LINE).lineWidth(1).stroke()
  doc.moveDown(0.6)
  doc.fillColor(MUTED).fontSize(8.5).font('Helvetica')
    .text('The original page structure, wording and photographs were preserved. Only the presentation layer was upgraded, so nothing familiar to your visitors was lost.', { width: W })
  doc.moveDown(0.4)
  doc.fillColor(MUTED).fontSize(8).text('Generated by ForgeAI', { width: W })

  doc.end()
}
